#!/usr/bin/env python3
"""
把 `ui-vue/dist/` 的构建产物生成成 Rust 可 `include_str!` 的资源表。

## 为什么需要这一步

内置 HTTP 服务要把前端托管给手机 / 浏览器。旧版是 6 个 `include_str!("../../ui/xxx")`
硬编码；Vite 产物带 hash 文件名（`base-DNkS_8TJ.js`），路径不再固定，
所以改成**构建时生成一张表**，运行时按路径查。

## 用法

    python3 scripts/gen-ui-assets.py

产出 `src-tauri/src/ui_assets.rs`（**生成文件，不要手改**）。
构建流程里在 `npm run build:vue` 之后、`cargo build` 之前跑一次。
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DIST = REPO / "ui-vue" / "dist"
OUT = REPO / "src-tauri" / "src" / "ui_assets.rs"

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".ttf": "font/ttf",
    ".map": "application/json; charset=utf-8",
}


def main() -> int:
    if not DIST.is_dir():
        print(f"error: {DIST} 不存在，先跑 npm run build:vue", file=sys.stderr)
        return 1

    files = sorted(p for p in DIST.rglob("*") if p.is_file())
    if not files:
        print(f"error: {DIST} 是空的", file=sys.stderr)
        return 1

    entries: list[str] = []
    for path in files:
        rel = path.relative_to(DIST).as_posix()
        content_type = CONTENT_TYPES.get(path.suffix.lower(), "application/octet-stream")
        # include_str! 用相对 src/ 的路径；dist 里的都是文本资源
        entries.append(
            f'    ("{rel}", "{content_type}", include_str!("../../ui-vue/dist/{rel}")),'
        )

    body = "\n".join(entries)
    source = f'''// @generated by scripts/gen-ui-assets.py —— 不要手改。
//
// 内置 HTTP 服务托管的前端资源（Vite 构建产物）。
// 手机端「电脑页」与浏览器远程访问走的就是这张表。
//
// 源目录：ui-vue/dist/
// 条目数：{len(files)}

/// (相对路径, Content-Type, 文件正文)
pub(crate) const UI_ASSETS: &[(&str, &str, &str)] = &[
{body}
];
'''
    OUT.write_text(source, encoding="utf-8")
    print(f"已生成 {OUT}（{len(files)} 个文件）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
